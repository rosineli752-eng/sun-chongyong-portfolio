#!/usr/bin/env python3
"""Create lightweight browsing images without changing any original asset.

Run from any directory: python tools/generate-responsive-images.py
Requires Pillow with WebP support. Outputs dist/assets/responsive/ and
dist/image-manifest.js. Existing originals remain the lightbox/download source.
"""

from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor
from io import BytesIO
import json
from pathlib import Path
import re

from PIL import Image, ImageOps


ROOT = Path(__file__).resolve().parents[1]
IMAGE_REF = re.compile(r"assets/[A-Za-z0-9_./-]+\.(?:webp|png|jpe?g)", re.I)
STATIC_REFS = {
    "assets/portrait.webp",
    "assets/works/works-02-full.webp",
    "assets/works/works-05-full.webp",
    "assets/qingjiang/qingjiang-14-full.webp",
}
TARGET_WIDTHS = (480, 960)
LARGE_TARGET_BYTES = 180 * 1024


def find_references(dist: Path) -> list[str]:
    refs = set(STATIC_REFS)
    for name in ("data.js", "index.html", "app.js"):
        refs.update(IMAGE_REF.findall((dist / name).read_text(encoding="utf-8")))
    # Do not recursively turn our own generated image URLs into sources.
    return sorted(ref for ref in refs if not ref.startswith("assets/responsive/"))


def encode(image: Image.Image, quality: int, icc: bytes | None) -> bytes:
    output = BytesIO()
    options = {"format": "WEBP", "quality": quality, "method": 6}
    if icc:
        options["icc_profile"] = icc
    image.save(output, **options)
    return output.getvalue()


def generate(ref: str, dist: Path) -> tuple[str, dict, dict]:
    source_path = dist / ref
    with Image.open(source_path) as source:
        icc = source.info.get("icc_profile")
        image = ImageOps.exif_transpose(source)
        if image.mode not in ("RGB", "RGBA"):
            image = image.convert("RGBA" if "transparency" in image.info else "RGB")
        width, height = image.size
        relative = Path(ref).relative_to("assets")
        destination = dist / "assets" / "responsive" / relative.parent
        destination.mkdir(parents=True, exist_ok=True)
        variants = []
        qualities = []
        actual_widths = sorted({min(target, width) for target in TARGET_WIDTHS})
        # Keep design lettering crisp; photos and existing covers start at 76.
        initial_quality = 76 if ref.startswith("assets/works/") or "cover" in relative.stem or "poster" in relative.stem else 78
        for target in actual_widths:
            target_height = max(1, round(height * target / width))
            resized = image.resize((target, target_height), Image.Resampling.LANCZOS)
            quality = initial_quality
            payload = encode(resized, quality, icc)
            # Reduce only within 72–78. Texture-heavy posters can exceed the
            # budget; retain their detail instead of aggressively blurring them.
            if target > 480:
                while len(payload) > LARGE_TARGET_BYTES and quality > 72:
                    quality -= 2
                    payload = encode(resized, quality, icc)
            filename = f"{relative.stem}-{target}.webp"
            output = destination / filename
            output.write_bytes(payload)
            variants.append({
                "src": output.relative_to(dist).as_posix(),
                "width": target,
                "height": target_height,
                "bytes": len(payload),
            })
            qualities.append(quality)

    entry = {
        "width": width,
        "height": height,
        "preview": variants[0]["src"],
        "srcset": ", ".join(f"{variant['src']} {variant['width']}w" for variant in variants),
        "variants": variants,
    }
    report = {
        "originalBytes": source_path.stat().st_size,
        "width": width,
        "height": height,
        "variants": [{**variant, "quality": quality} for variant, quality in zip(variants, qualities)],
    }
    return ref, entry, report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dist", type=Path, default=ROOT / "dist")
    parser.add_argument("--workers", type=int, default=4)
    args = parser.parse_args()
    dist = args.dist.resolve()
    refs = find_references(dist)
    missing = [ref for ref in refs if not (dist / ref).is_file()]
    if missing:
        raise FileNotFoundError("Missing source images: " + ", ".join(missing))

    with ThreadPoolExecutor(max_workers=max(1, args.workers)) as pool:
        results = list(pool.map(lambda ref: generate(ref, dist), refs))
    manifest = {ref: entry for ref, entry, _ in results}
    reports = {ref: report for ref, _, report in results}
    (dist / "image-manifest.js").write_text(
        "// Generated by tools/generate-responsive-images.py; keep originals for full-size viewing.\n"
        "window.IMAGE_MANIFEST = " + json.dumps(manifest, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    original_bytes = sum(report["originalBytes"] for report in reports.values())
    small_bytes = sum(report["variants"][0]["bytes"] for report in reports.values())
    large_bytes = sum(report["variants"][-1]["bytes"] for report in reports.values())
    oversized = [
        {"ref": ref, **report["variants"][-1]}
        for ref, report in reports.items()
        if report["variants"][-1]["bytes"] > LARGE_TARGET_BYTES
    ]
    summary = {
        "imageCount": len(refs),
        "variantCount": sum(len(report["variants"]) for report in reports.values()),
        "originalBytes": original_bytes,
        "preview480Bytes": small_bytes,
        "browse960Bytes": large_bytes,
        "browse960ReductionPercent": round((1 - large_bytes / original_bytes) * 100, 2),
        "over180KiB": oversized,
    }
    (ROOT / "tools" / "responsive-image-report.json").write_text(
        json.dumps({"summary": summary, "images": reports}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
